#!/usr/bin/env python3
"""harvest_results.py - 实验结果收割器。

扫描实验/结果根目录下各 run 目录的日志文件，抽取验证/测试指标
(psnr/ssim 及日志中出现的其他指标)，聚合输出:

1. ``metrics.yaml``   结构化结果(每条记录绑定 run/指标/值/iter/来源日志)
2. stdout 打印 Markdown 表格(每个 (run, dataset) 一行，取最后一次记录值)
3. ``--latex`` 时另写 ``<output_stem>.tex`` 并打印 LaTeX 表格

解析依据的真实日志格式(请勿臆造，见括号内代码位置):

- 日志行前缀 ``%(asctime)s %(levelname)s: %(message)s``
  (basicsr/utils/logger.py get_root_logger);多行消息仅首行带前缀。
- 训练进度行 ``[exp..][epoch:  1, iter:    5,000, lr:(...)] ...``
  (basicsr/utils/logger.py MessageLogger.__call__);iter 带千分位逗号。
- 验证聚合块 (basicofr/models/rtn_model.py:1037-1050)::

    2024-05-01 12:00:12,000 INFO: Validation OldFilmval
    \\t# psnr: 25.1234\\tBest: 25.1234 @ 5000 iter
    \\t# ssim: 0.8123\\tBest: 0.8200 @ 4000 iter

- FID 行 (basicofr/models/rtn_model.py:217): ``\\t # fid: 12.3456`` (无 Best)。
- run 目录 = ``<experiments_root>/<name>/``，内含
  ``train_{name}_{ts}.log`` / ``test_{name}_{ts}.log`` 及 yml 配置副本
  (basicsr/utils/options.py parse_options / copy_opt_file)。

验证时的 iter 不在 Validation 块内，取该块之前最后一条训练进度行的
iter(val 触发点 current_iter % val_freq == 0 恰有进度行);test 日志无
进度行时 iter 为 null。

fail-closed 约定:
- 目标 metrics.yaml 已存在且内容将改变时，不加 --force 则打印 diff
  摘要并以非零码退出;
- 解析不到任何指标时以非零码退出。

仅依赖标准库 + pyyaml;不 import torch。

用法:
    python3 scripts/harvest_results.py [--root Exp/experiments]
        [--output <path>] [--force] [--latex] [--selftest]
"""

import argparse
import difflib
import re
import subprocess
import sys
import tempfile
from pathlib import Path

import yaml

# ---------------------------------------------------------------- 日志格式正则

# 训练进度行: [rtn_r..][epoch:  1, iter:    5,000, lr:(2.000e-04,)] ...
RE_PROGRESS_ITER = re.compile(r'\[epoch:\s*\d+,\s*iter:\s*([\d,]+),')

# Validation 块首行(带日志前缀): "... INFO: Validation OldFilmval"
RE_VAL_HEADER = re.compile(r'INFO:\s+Validation\s+(\S+)\s*$')

# 新日志行(asctime 开头)用于判定 Validation 块结束
RE_LOG_LINE_START = re.compile(r'^\d{4}-\d{2}-\d{2}\s')

# 指标行(多行消息的后续行,无前缀,以 tab 开头):
#   "\t# psnr: 25.1234\tBest: 25.1234 @ 5000 iter"   (聚合指标)
#   "\t # fid: 12.3456"                              (FID, 无 Best)
RE_METRIC_LINE = re.compile(
    r'^\s*#\s*([A-Za-z0-9_]+):\s*([0-9.eE+\-]+)'
    r'(?:\s*Best:\s*([0-9.eE+\-]+)\s*@\s*(\S+)\s*iter)?\s*$')

# 表格列的偏好顺序(其余指标按字母序追加)
PREFERRED_METRIC_ORDER = [
    'psnr', 'ssim', 'lpips', 'dists', 'ms_ssim', 'fid',
    'niqe', 'brisque', 'clipiqa',
]

YAML_HEADER = (
    '# Generated by scripts/harvest_results.py. DO NOT EDIT BY HAND.\n'
    '# 论文中的数字必须来自本文件(绑定 run/配置/来源日志),禁止手抄日志。\n')

EXIT_OK = 0
EXIT_NO_METRICS = 2
EXIT_REFUSE_OVERWRITE = 3


# ---------------------------------------------------------------- 解析

def _to_int(text):
    """尽力转 int(去千分位逗号);失败返回原字符串。"""
    try:
        return int(str(text).replace(',', ''))
    except ValueError:
        return text


def _to_int_or_none(text):
    """转 int;非数字(如 test 日志中 Best 行为 run 名)返回 None,不污染 receipt。"""
    try:
        return int(str(text).replace(',', ''))
    except ValueError:
        return None


def parse_log(log_path):
    """解析单个日志文件,返回指标记录列表(按出现顺序)。

    每条记录: dict(dataset, metric, value, iter, best, best_iter, line)
    - iter: 该 Validation 块之前最后一条进度行的 iter;无进度行为 None
    - best/best_iter: 日志中 "Best: X @ Y iter" 的值;FID 等无此行时为 None
    - line: 来源行号(1-based)
    """
    records = []
    last_iter = None
    current_dataset = None
    with open(log_path, 'r', encoding='utf-8', errors='replace') as f:
        for lineno, raw in enumerate(f, 1):
            line = raw.rstrip('\n')

            m = RE_PROGRESS_ITER.search(line)
            if m:
                last_iter = _to_int(m.group(1))
                current_dataset = None
                continue

            mh = RE_VAL_HEADER.search(line)
            if mh:
                current_dataset = mh.group(1)
                continue

            if RE_LOG_LINE_START.match(line):
                # 其他带时间戳的日志行:结束当前 Validation 块
                current_dataset = None
                continue

            mm = RE_METRIC_LINE.match(line)
            if mm and current_dataset is not None:
                records.append({
                    'dataset': current_dataset,
                    'metric': mm.group(1),
                    'value': float(mm.group(2)),
                    'iter': last_iter,
                    'best': float(mm.group(3)) if mm.group(3) is not None else None,
                    'best_iter': _to_int_or_none(mm.group(4)) if mm.group(4) is not None else None,
                    'line': lineno,
                })
    return records


def discover_run_dirs(root):
    """发现 root 下的 run 目录(含 *.log 的子目录;root 自身直接含日志也算)。"""
    root = Path(root)
    runs = {}
    if any(root.glob('*.log')):
        runs[root.name] = root
    for child in sorted(root.iterdir()):
        if child.is_dir() and any(child.glob('*.log')):
            runs[child.name] = child
    return runs


def find_config_files(run_dir):
    """run 目录里的 yml 配置副本文件名列表(train.py 会复制配置到 run 根)。"""
    names = [p.name for p in sorted(Path(run_dir).glob('*.yml'))]
    names += [p.name for p in sorted(Path(run_dir).glob('*.yaml'))]
    return names


def harvest(root):
    """扫描 root,返回结构化结果 dict。"""
    root = Path(root)
    doc = {
        'root': str(root.resolve()),
        'runs': {},
    }
    total = 0
    for run_name, run_dir in discover_run_dirs(root).items():
        configs = find_config_files(run_dir)
        run_entry = {
            'config': configs[0] if configs else None,
            'logs': [],
            'metrics': [],
        }
        for log_path in sorted(run_dir.glob('*.log')):
            records = parse_log(log_path)
            if records:
                run_entry['logs'].append(log_path.name)
            for rec in records:
                rec['log'] = str(log_path)
                run_entry['metrics'].append(rec)
        total += len(run_entry['metrics'])
        run_entry['metric_count'] = len(run_entry['metrics'])
        doc['runs'][run_name] = run_entry
    doc['total_records'] = total
    return doc


# ---------------------------------------------------------------- 输出

def render_yaml(doc):
    return YAML_HEADER + yaml.safe_dump(
        doc, allow_unicode=True, sort_keys=True, default_flow_style=False)


def _ordered_metric_columns(doc):
    seen = []
    for run_entry in doc['runs'].values():
        for rec in run_entry['metrics']:
            if rec['metric'] not in seen:
                seen.append(rec['metric'])
    ordered = [m for m in PREFERRED_METRIC_ORDER if m in seen]
    ordered += sorted(m for m in seen if m not in PREFERRED_METRIC_ORDER)
    return ordered


def _final_records(doc):
    """每个 (run, dataset, metric) 取日志中最后一次出现的记录。"""
    rows = []
    for run_name, run_entry in doc['runs'].items():
        by_dataset = {}
        for rec in run_entry['metrics']:
            by_dataset.setdefault(rec['dataset'], {})[rec['metric']] = rec
        for dataset in sorted(by_dataset):
            rows.append((run_name, dataset, by_dataset[dataset]))
    return rows


def render_markdown(doc):
    cols = _ordered_metric_columns(doc)
    header = ['run', 'dataset', 'iter'] + cols
    lines = [
        '| ' + ' | '.join(header) + ' |',
        '|' + '|'.join(['---'] * len(header)) + '|',
    ]
    for run_name, dataset, recs in _final_records(doc):
        iters = [r['iter'] for r in recs.values() if r['iter'] is not None]
        iter_str = str(max(iters)) if iters else '-'
        cells = [run_name, dataset, iter_str]
        for col in cols:
            rec = recs.get(col)
            cells.append(f"{rec['value']:.4f}" if rec else '-')
        lines.append('| ' + ' | '.join(cells) + ' |')
    return '\n'.join(lines)


def _latex_escape(text):
    return str(text).replace('_', r'\_')


def render_latex(doc):
    cols = _ordered_metric_columns(doc)
    col_spec = 'llr' + 'r' * len(cols)
    header = ['run', 'dataset', 'iter'] + cols
    lines = [
        r'\begin{tabular}{' + col_spec + '}',
        r'\toprule',
        ' & '.join(header) + r' \\',
        r'\midrule',
    ]
    for run_name, dataset, recs in _final_records(doc):
        iters = [r['iter'] for r in recs.values() if r['iter'] is not None]
        iter_str = str(max(iters)) if iters else '-'
        cells = [
            r'\texttt{' + _latex_escape(run_name) + '}',
            _latex_escape(dataset),
            iter_str,
        ]
        for col in cols:
            rec = recs.get(col)
            cells.append(f"{rec['value']:.4f}" if rec else '-')
        lines.append(' & '.join(cells) + r' \\')
    lines += [r'\bottomrule', r'\end{tabular}']
    return '\n'.join(lines)


def emit_output(yaml_text, output_path, force):
    """fail-closed 写出 metrics.yaml。

    返回 (exit_code, wrote: bool)。已存在且内容不同且无 --force 时,
    打印 diff 摘要并返回 EXIT_REFUSE_OVERWRITE,不写文件。
    """
    output_path = Path(output_path)
    if output_path.exists():
        old_text = output_path.read_text(encoding='utf-8')
        if old_text == yaml_text:
            print(f'[harvest] unchanged: {output_path} (内容一致,未重写)')
            return EXIT_OK, False
        if not force:
            diff = list(difflib.unified_diff(
                old_text.splitlines(), yaml_text.splitlines(),
                fromfile=str(output_path), tofile='<new>', lineterm=''))
            print(f'[harvest] REFUSED: {output_path} 已存在且内容将改变。'
                  f'确认后请加 --force 覆盖。diff 摘要(前 40 行):', file=sys.stderr)
            for line in diff[:40]:
                print(line, file=sys.stderr)
            if len(diff) > 40:
                print(f'... (共 {len(diff)} 行 diff,截断)', file=sys.stderr)
            return EXIT_REFUSE_OVERWRITE, False
    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(yaml_text, encoding='utf-8')
    print(f'[harvest] wrote: {output_path}')
    return EXIT_OK, True


