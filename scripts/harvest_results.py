def _selftest_check(cond, msg):
    if not cond:
        raise AssertionError(f'selftest failed: {msg}')


def run_selftest():
    """在临时目录构造合成 run 目录,验证解析与 fail-closed 行为。"""
    script = Path(__file__).resolve()
    with tempfile.TemporaryDirectory(prefix='harvest_selftest_') as tmp:
        root = Path(tmp) / 'experiments'
        run_a = root / 'run_a'
        run_b = root / 'run_b'
        (root / 'empty_run').mkdir(parents=True)
        run_a.mkdir(parents=True)
        run_b.mkdir(parents=True)
        (run_a / 'rtn_baseline.yml').write_text('name: run_a\n', encoding='utf-8')
        (run_a / 'train_run_a_20240501_120000.log').write_text(
            _SELTEST_LOG_A, encoding='utf-8')
        (run_b / 'test_run_b_20240502_090000.log').write_text(
            _SELTEST_LOG_B, encoding='utf-8')

        # ---- 1. 解析正确性 ----
        doc = harvest(root)
        _selftest_check(doc['total_records'] == 7,
                        f"total_records={doc['total_records']} != 7")
        ra = doc['runs']['run_a']
        _selftest_check(ra['config'] == 'rtn_baseline.yml', 'run_a config not bound')
        vals = {(r['metric'], r['iter']): r for r in ra['metrics']}
        _selftest_check(vals[('psnr', 5000)]['value'] == 25.1234, 'run_a psnr@5000')
        _selftest_check(vals[('ssim', 5000)]['best'] == 0.8200
                        and vals[('ssim', 5000)]['best_iter'] == 4000,
                        'run_a ssim best@4000')
        _selftest_check(vals[('psnr', 10000)]['value'] == 25.5678, 'run_a psnr@10000')
        fids = [r for r in ra['metrics'] if r['metric'] == 'fid']
        _selftest_check(len(fids) == 1 and fids[0]['value'] == 12.3456
                        and fids[0]['best'] is None, 'run_a fid line')
        rb = doc['runs']['run_b']
        _selftest_check(all(r['iter'] is None for r in rb['metrics']),
                        'run_b (test log) iter should be None')
        _selftest_check(all(r['best_iter'] is None for r in rb['metrics']),
                        'run_b (test log) non-numeric best_iter should be None')
        for rec in ra['metrics']:
            _selftest_check(rec['log'].endswith('train_run_a_20240501_120000.log'),
                            'source log path bound')
        md = render_markdown(doc)
        _selftest_check('| run | dataset | iter | psnr | ssim | fid |' in md,
                        'markdown header')
        _selftest_check('| run_a | OldFilmval | 10000 | 25.5678 | 0.8201 | 12.3456 |'
                        in md, 'markdown final row')
        tex = render_latex(doc)
        _selftest_check(r'run\_a' in tex and r'\toprule' in tex, 'latex render')

        # ---- 2. fail-closed(CLI 级) ----
        out = root / 'metrics.yaml'

        def cli(*extra):
            return subprocess.run(
                [sys.executable, str(script), '--root', str(root), *extra],
                capture_output=True, text=True)

        p = cli()
        _selftest_check(p.returncode == 0 and out.exists(),
                        f'first run rc={p.returncode}: {p.stderr}')
        p = cli()
        _selftest_check(p.returncode == 0 and 'unchanged' in p.stdout,
                        'idempotent rerun should be unchanged')
        # 修改日志(新增一次验证) → 无 --force 必须拒绝
        with open(run_a / 'train_run_a_20240501_120000.log', 'a', encoding='utf-8') as f:
            f.write('2024-05-01 12:20:10,000 INFO: [run_a..][epoch:  3, iter:   15,000, '
                    'lr:(5.000e-05,)] l_g_pix: 9.0000e-02\n'
                    '2024-05-01 12:20:12,000 INFO: Validation OldFilmval\n'
                    '\t# psnr: 25.9999\tBest: 25.9999 @ 15000 iter\n')
        p = cli()
        _selftest_check(p.returncode == EXIT_REFUSE_OVERWRITE and 'REFUSED' in p.stderr,
                        f'fail-closed rc={p.returncode}: {p.stderr[:200]}')
        p = cli('--force')
        _selftest_check(p.returncode == 0, f'--force rc={p.returncode}: {p.stderr}')
        doc2 = yaml.safe_load(out.read_text(encoding='utf-8'))
        _selftest_check(doc2['total_records'] == 8, 'force rerun picked up new record')

        # ---- 3. 解析不到指标 → 非零 ----
        empty_root = Path(tmp) / 'empty'
        (empty_root / 'run_x').mkdir(parents=True)
        (empty_root / 'run_x' / 'train_run_x_20240501_000000.log').write_text(
            '2024-05-01 00:00:00,000 INFO: no metrics here\n', encoding='utf-8')
        p = subprocess.run(
            [sys.executable, str(script), '--root', str(empty_root)],
            capture_output=True, text=True)
        _selftest_check(p.returncode == EXIT_NO_METRICS,
                        f'empty root rc={p.returncode}')

    print('[selftest] ALL PASSED: parse / markdown / latex / fail-closed / empty-root')
    return EXIT_OK


# ---------------------------------------------------------------- main

def resolve_root(arg_root):
    """默认 Exp/experiments,回退仓根的 experiments;显式 --root 必须存在。"""
    if arg_root is not None:
        root = Path(arg_root)
        if not root.is_dir():
            print(f'[harvest] ERROR: --root 不存在或不是目录: {arg_root}', file=sys.stderr)
            sys.exit(EXIT_NO_METRICS)
        return root
    for cand in ('Exp/experiments', 'experiments'):
        if Path(cand).is_dir():
            return Path(cand)
    print('[harvest] ERROR: 未找到默认结果目录(尝试过 Exp/experiments, experiments);'
          '请用 --root 指定。', file=sys.stderr)
    sys.exit(EXIT_NO_METRICS)


def default_output(root):
    """默认输出位置:Exp/experiments 被 .gitignore 忽略,收据必须落在可提交的
    Exp/metrics.yaml;其他 root 默认 <root>/metrics.yaml。"""
    if root.name == 'experiments' and root.parent.name == 'Exp':
        return root.parent / 'metrics.yaml'
    return root / 'metrics.yaml'


def main(argv=None):
    parser = argparse.ArgumentParser(
        description='聚合各 run 日志中的验证/测试指标 → metrics.yaml + Markdown/LaTeX 表格')
    parser.add_argument('--root', default=None,
                        help='实验/结果根目录(默认 Exp/experiments,回退 experiments)')
    parser.add_argument('--output', default=None,
                        help='metrics.yaml 输出路径(默认 Exp/metrics.yaml;自定义 root 时为 <root>/metrics.yaml)')
    parser.add_argument('--force', action='store_true',
                        help='允许覆盖内容已变化的 metrics.yaml')
    parser.add_argument('--latex', action='store_true',
                        help='另输出 LaTeX 表格(打印并写 <output_stem>.tex)')
    parser.add_argument('--selftest', action='store_true',
                        help='用合成日志 fixture 自测解析与 fail-closed 行为')
    args = parser.parse_args(argv)

    if args.selftest:
        return run_selftest()

    root = resolve_root(args.root)
    output = Path(args.output) if args.output else default_output(root)

    doc = harvest(root)
    if doc['total_records'] == 0:
        print(f'[harvest] ERROR: 在 {root} 下未解析到任何验证/测试指标记录。\n'
              f'  预期日志形如 train_*.log / test_*.log,内含 '
              f'"Validation <dataset>" 块与 "\\t# <metric>: <val>" 行。', file=sys.stderr)
        return EXIT_NO_METRICS

    code, wrote = emit_output(render_yaml(doc), output, args.force)
    if code != EXIT_OK:
        return code

    if args.latex:
        tex = render_latex(doc)
        tex_path = output.with_suffix('.tex')
        tex_path.write_text(tex + '\n', encoding='utf-8')
        print(f'[harvest] wrote: {tex_path}')

    n_runs = sum(1 for r in doc['runs'].values() if r['metric_count'] > 0)
    print(f"[harvest] {doc['total_records']} records from {n_runs} run(s) under {root}")
    print()
    print(render_markdown(doc))
    if args.latex:
        print()
        print(render_latex(doc))
    return EXIT_OK


if __name__ == '__main__':
    sys.exit(main())
